const trendTitle = document.getElementById("trend-title");
const trendDescription = document.getElementById("trend-description");
const trendTemplate = document.getElementById("card-template");
const dropTemplate = document.getElementById("drop-template");
const dropList = document.getElementById("drop-list");
const lookTemplate = document.getElementById("look-template");
const lookbookGrid = document.getElementById("lookbook");
const themeToggle = document.getElementById("theme-toggle");

function renderTrend(mood, occasion) {
  const trend = trends[mood][occasion];
  trendTitle.textContent = trend.title;
  trendDescription.textContent = trend.description;

  cardsContainer.innerHTML = "";

  trend.items.forEach((item) => {
    const card = trendTemplate.content.cloneNode(true);
    card.querySelector(".card__tag").textContent = item.tag;
    card.querySelector(".card__title").textContent = item.title;
    card.querySelector(".card__brand").textContent = item.brand;
    card.querySelector(".card__price").textContent = item.price;
    cardsContainer.appendChild(card);
  });
}

function renderDrops() {
  drops.forEach((drop) => {
    const entry = dropTemplate.content.cloneNode(true);
    entry.querySelector(".drop__time").textContent = drop.time;
    entry.querySelector(".drop__title").textContent = drop.title;
    entry.querySelector(".drop__meta").textContent = drop.meta;
    dropList.appendChild(entry);
  });
}

function renderLookbook() {
  lookbook.forEach((look) => {
    const entry = lookTemplate.content.cloneNode(true);
    entry.querySelector(".look__title").textContent = look.title;
    entry.querySelector(".look__caption").textContent = look.caption;
    const image = entry.querySelector(".look__image");
    image.style.backgroundImage = `linear-gradient(135deg, rgba(15, 15, 50, 0.2), transparent 55%), url("https://source.unsplash.com/featured/?fashion,${encodeURIComponent(
      look.title
    )}")`;
    image.style.backgroundSize = "cover";
    image.style.backgroundPosition = "center";
    lookbookGrid.appendChild(entry);
  });
}

function initThemeToggle() {
  const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
  if (prefersDark) {
    document.body.setAttribute("data-theme", "dark");
    themeToggle.textContent = "☀️";
  }

  themeToggle.addEventListener("click", () => {
    const isDark = document.body.getAttribute("data-theme") === "dark";
    document.body.setAttribute("data-theme", isDark ? "light" : "dark");
    themeToggle.textContent = isDark ? "🌙" : "☀️";
  });
}

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(form);
  const mood = formData.get("mood");
  const occasion = formData.get("occasion");
  renderTrend(mood, occasion);
});

